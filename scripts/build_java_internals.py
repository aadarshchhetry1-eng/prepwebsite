"""
build_java_internals.py
Aggregates all 55 Java Internal Working topics and builds js/data/java-internals-data.js
"""

import json
import os
import sys

sys.path.append(os.path.join(os.path.dirname(__file__)))
from java_internals_data1 import TOPICS_1_TO_14
from java_internals_data2 import TOPICS_15_TO_28
from java_internals_data3 import TOPICS_29_TO_42
from java_internals_data4 import TOPICS_43_TO_55

ALL_TOPICS = TOPICS_1_TO_14 + TOPICS_15_TO_28 + TOPICS_29_TO_42 + TOPICS_43_TO_55

CATEGORIES = [
    {
        "id": "jvm_memory",
        "title": "☕ JVM Memory & Garbage Collection",
        "count": 6
    },
    {
        "id": "classloading",
        "title": "⚙️ Class Loading & JIT Execution",
        "count": 8
    },
    {
        "id": "jmm",
        "title": "🧵 Java Memory Model & Threads",
        "count": 7
    },
    {
        "id": "concurrency",
        "title": "⚡ Advanced Concurrency & Synchronizers",
        "count": 10
    },
    {
        "id": "collections",
        "title": "📦 Collections Framework Internals",
        "count": 9
    },
    {
        "id": "strings",
        "title": "🔤 Strings & Object Semantics",
        "count": 9
    },
    {
        "id": "io_nio",
        "title": "💾 I/O, NIO & Serialization",
        "count": 6
    }
]

def build():
    print(f"Total Java Internals deep dives: {len(ALL_TOPICS)}")
    
    # Validation
    ids = set()
    for idx, t in enumerate(ALL_TOPICS):
        tid = t["id"]
        if tid in ids:
            raise ValueError(f"Duplicate id found: {tid}")
        ids.add(tid)
        
        required_fields = ["id", "title", "category", "badge", "oneLiner", "whatIsIt", 
                           "visualDiagram", "internalWorking", "complexPart", "keyPoints", 
                           "codeSnippet", "pitfall", "interviewTip"]
        for field in required_fields:
            if field not in t or not t[field]:
                raise ValueError(f"Topic {tid} missing field: {field}")
    
    output_path = os.path.join(os.path.dirname(__file__), "..", "js", "data", "java-internals-data.js")
    output_path = os.path.abspath(output_path)
    
    js_content = """/**
 * java-internals-data.js
 * 55 Complete Core Java Internal Working Engine Deep Dives
 * Complete with Visual Flow Diagrams, Under-The-Hood JVM Mechanics, and Staff-Level Traps.
 * Auto-generated by build_java_internals.py
 */

window.REVISION_APP_DATA = window.REVISION_APP_DATA || {};

// Categories for Java Internals Explorer
window.REVISION_APP_DATA.JAVA_INTERNALS_CATEGORIES = """ + json.dumps(CATEGORIES, indent=2) + """;

// Full list of 55 Java Internal Working Deep Dives
window.REVISION_APP_DATA.JAVA_INTERNALS = """ + json.dumps(ALL_TOPICS, indent=2) + """;

// O(1) Map Lookup by ID
window.REVISION_APP_DATA.JAVA_INTERNALS_MAP = {};
window.REVISION_APP_DATA.JAVA_INTERNALS.forEach(function(item) {
  window.REVISION_APP_DATA.JAVA_INTERNALS_MAP[item.id] = item;
});
"""

    with open(output_path, "w", encoding="utf-8") as f:
        f.write(js_content)
        
    file_size = os.path.getsize(output_path)
    print(f"Successfully generated {output_path} ({file_size:,} bytes, {len(ALL_TOPICS)} topics)")

if __name__ == "__main__":
    build()
