"""
Build script to aggregate all 29 Spring Boot Internals topics with complete visual diagrams
Outputs: js/data/springboot-internals-data.js
"""

import sys
import os
import json

sys.path.append(os.path.dirname(os.path.abspath(__file__)))

import sb_internals_data1
import sb_internals_data2
import sb_internals_data3

CATEGORIES = [
    {"id": "bootstrap", "title": "🚀 Bootstrap & Startup Engine", "count": 8},
    {"id": "dependencies", "title": "🧩 Auto-Config & Dependencies", "count": 4},
    {"id": "ioc", "title": "🔄 Core IoC, Lifecycle & Proxies", "count": 6},
    {"id": "config", "title": "⚙️ Configuration & Properties", "count": 4},
    {"id": "web", "title": "🌐 Web, Server, Observability & Testing", "count": 7},
]

def main():
    all_internals = (
        sb_internals_data1.TOPICS_PART1 +
        sb_internals_data2.TOPICS_PART2 +
        sb_internals_data3.TOPICS_PART3
    )

    print(f"Total Spring Boot Internals aggregated: {len(all_internals)}")
    assert len(all_internals) == 29, f"Expected 29 topics, got {len(all_internals)}"

    internals_map = {t["id"]: t for t in all_internals}

    js_output_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "js", "data", "springboot-internals-data.js")
    js_output_path = os.path.normpath(js_output_path)

    js_content = """/**
 * springboot-internals-data.js
 * 29 In-depth Spring Boot Internal Working Engine Deep Dives
 * Complete with Visual Flow Diagrams, Under-The-Hood Mechanics, and Complex Staff Traps.
 * Auto-generated by build_springboot_internals.py
 */

window.REVISION_APP_DATA = window.REVISION_APP_DATA || {};

// Categories for Spring Boot Internals Explorer
window.REVISION_APP_DATA.SPRING_INTERNALS_CATEGORIES = """ + json.dumps(CATEGORIES, indent=2) + """;

// Full list of 29 Internal Working Deep Dives
window.REVISION_APP_DATA.SPRING_INTERNALS = """ + json.dumps(all_internals, indent=2) + """;

// Map by ID for fast lookup and modal rendering
window.REVISION_APP_DATA.SPRING_INTERNALS_MAP = """ + json.dumps(internals_map, indent=2) + """;
"""

    with open(js_output_path, "w", encoding="utf-8") as f:
        f.write(js_content)

    print(f"Successfully wrote {os.path.getsize(js_output_path):,} bytes to {js_output_path}")

if __name__ == "__main__":
    main()
