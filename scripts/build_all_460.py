"""
Build script to aggregate all 46 Core Java topics (10 tricky questions each = 460 questions)
Outputs: js/data/java-topic-questions.js
"""

import sys
import os
import json

# Ensure scripts dir in path
sys.path.append(os.path.dirname(os.path.abspath(__file__)))

import topics_oop
import topics_strings
import topics_collections
import topics_concurrency
import topics_java8
import topics_jvm
import topics_edge

CATEGORIES = [
    {"id": "oop", "title": "OOP & Design", "icon": "fa-cubes", "color": "#38bdf8"},
    {"id": "strings", "title": "Strings, Wrappers & Exceptions", "icon": "fa-font", "color": "#a78bfa"},
    {"id": "collections", "title": "Collections", "icon": "fa-layer-group", "color": "#34d399"},
    {"id": "concurrency", "title": "Multithreading & Concurrency", "icon": "fa-bolt", "color": "#f59e0b"},
    {"id": "java8", "title": "Java 8+ Features", "icon": "fa-code-branch", "color": "#ec4899"},
    {"id": "jvm", "title": "JVM Internals & Memory", "icon": "fa-microchip", "color": "#06b6d4"},
    {"id": "edge", "title": "Tricky Edge Cases", "icon": "fa-triangle-exclamation", "color": "#ef4444"},
]

def main():
    topic_lists = [
        ("oop", topics_oop.TOPICS_OOP),
        ("strings", topics_strings.TOPICS_STRINGS),
        ("collections", topics_collections.TOPICS_COLLECTIONS),
        ("concurrency", topics_concurrency.TOPICS_CONCURRENCY),
        ("java8", topics_java8.TOPICS_JAVA8),
        ("jvm", topics_jvm.TOPICS_JVM),
        ("edge", topics_edge.TOPICS_EDGE),
    ]

    all_topics = []
    all_questions = []
    topic_map = {}

    for cat_id, topics in topic_lists:
        for t in topics:
            t_copy = {
                "topicId": t["topicId"],
                "topicTitle": t["topicTitle"],
                "category": t["category"],
                "summary": t["summary"],
                "questionCount": len(t["questions"]),
            }
            questions = []
            for q in t["questions"]:
                q_aug = dict(q)
                q_aug["topicId"] = t["topicId"]
                q_aug["topicTitle"] = t["topicTitle"]
                q_aug["category"] = t["category"]
                # Ensure seniorAnswer is a list if it was a string
                if isinstance(q_aug.get("seniorAnswer"), str):
                    q_aug["seniorAnswer"] = [q_aug["seniorAnswer"]]
                questions.append(q_aug)
                all_questions.append(q_aug)

            t_copy["questions"] = questions
            all_topics.append(t_copy)
            topic_map[t["topicId"]] = questions

    print(f"Total topics aggregated: {len(all_topics)}")
    print(f"Total questions aggregated: {len(all_questions)}")
    assert len(all_topics) == 46, f"Expected 46 topics, got {len(all_topics)}"
    assert len(all_questions) == 460, f"Expected 460 questions, got {len(all_questions)}"

    for t in all_topics:
        assert len(t["questions"]) == 10, f"Topic {t['topicId']} has {len(t['questions'])} questions (expected 10)"

    js_output_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "js", "data", "java-topic-questions.js")
    js_output_path = os.path.normpath(js_output_path)

    js_content = """/**
 * java-topic-questions.js
 * Comprehensive 46-Topic Core Java Tricky Question Bank (460 Questions Total)
 * 10 Tricky, Senior/Staff Level Interview Questions Per Individual Topic.
 * Auto-generated by build_all_460.py
 */

window.REVISION_APP_DATA = window.REVISION_APP_DATA || {};

// Metadata for the 7 primary categories
window.REVISION_APP_DATA.JAVA_460_CATEGORIES = """ + json.dumps(CATEGORIES, indent=2) + """;

// List of all 46 individual subtopics with their 10 tricky questions embedded
window.REVISION_APP_DATA.JAVA_460_TOPICS = """ + json.dumps(all_topics, indent=2) + """;

// Fast Map: topicId -> [10 questions]
window.REVISION_APP_DATA.JAVA_TOPIC_MAP = """ + json.dumps(topic_map, indent=2) + """;

// Flattened list of all 460 questions for search, filtering, and study mode
window.REVISION_APP_DATA.JAVA_460_QUESTIONS = """ + json.dumps(all_questions, indent=2) + """;

// Backwards compatibility for existing views
window.REVISION_APP_DATA.JAVA_TRICKY_QUESTIONS = window.REVISION_APP_DATA.JAVA_460_QUESTIONS;
"""

    with open(js_output_path, "w", encoding="utf-8") as f:
        f.write(js_content)

    print(f"Successfully wrote {os.path.getsize(js_output_path):,} bytes to {js_output_path}")

if __name__ == "__main__":
    main()
